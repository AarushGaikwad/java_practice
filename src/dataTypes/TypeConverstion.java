package dataTypes;

public class TypeConverstion {

	public static void main(String[] args) {
		int num = 100;
		double doubleNum = num; //integer is converted in double
		
		System.out.println(doubleNum);
		
		double d = 100.03;
		int a = (int) d;  //double is converted in integer value
		
		System.out.println(a);

	}

}
